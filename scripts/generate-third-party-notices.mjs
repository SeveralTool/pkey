#!/usr/bin/env node
/**
 * Generates docs/legal/THIRD_PARTY_NOTICES.generated.md from npm dependency licenses.
 * Requires: npx license-checker (dev dependency or one-off npx).
 *
 * Usage: node scripts/generate-third-party-notices.mjs
 */
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'docs', 'legal', 'THIRD_PARTY_NOTICES.generated.md');

const json = execSync(
  'npx --yes license-checker@25 --production --json --excludePrivatePackages',
  { cwd: root, encoding: 'utf8', maxBuffer: 10 * 1024 * 1024 }
);

/** @type {Record<string, { licenses?: string; repository?: string; publisher?: string }>} */
const packages = JSON.parse(json);
const rows = Object.entries(packages)
  .map(([name, meta]) => {
    const license = meta.licenses ?? 'UNKNOWN';
    const repo = meta.repository ?? '';
    return `| ${name} | ${license} | ${repo} |`;
  })
  .sort();

const body = `# Third-Party Notices (generated)

> Auto-generated by \`node scripts/generate-third-party-notices.mjs\`. Do not edit by hand.
> Merge or review before each store release.

| Package | License | Repository |
|---------|---------|------------|
${rows.join('\n')}
`;

writeFileSync(out, body, 'utf8');
console.log(`Wrote ${out} (${rows.length} packages)`);
